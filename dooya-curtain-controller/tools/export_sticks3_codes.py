#!/usr/bin/env python3

import argparse
import collections
import glob
import hashlib
import os
import re

from analyze_rfraw import read_capture


SLOT_PATTERN = re.compile(r"latest_curtain_(\d{2})_(up|stop|down)\.rfraw$")
ACTION_ORDER = {"up": 0, "stop": 1, "down": 2}


def valid_frame_at(edges, sync):
    if sync == 0 or sync + 144 >= len(edges):
        return False
    if not (
        edges[sync - 1][1] == 0
        and 7000 <= edges[sync - 1][0] <= 14000
        and edges[sync][1] == 1
        and 4500 <= edges[sync][0] <= 5100
        and edges[sync + 1][1] == 0
        and 1200 <= edges[sync + 1][0] <= 1700
    ):
        return False
    for bit in range(71):
        high = edges[sync + 2 + bit * 2]
        low = edges[sync + 3 + bit * 2]
        short_pulse = min(high[0], low[0])
        long_pulse = max(high[0], low[0])
        if not (
            high[1] == 1
            and low[1] == 0
            and 250 <= short_pulse <= 450
            and 600 <= long_pulse <= 850
        ):
            return False
    terminal = edges[sync + 144]
    return terminal[1] == 1 and 250 <= terminal[0] <= 850


def decode_payload(edges, sync):
    return "".join(
        "1" if edges[sync + 2 + bit * 2][0] > edges[sync + 3 + bit * 2][0] else "0"
        for bit in range(71)
    )


def extract_slot(path):
    capture = read_capture(path)
    edges = capture["edges"]
    syncs = [
        sync
        for sync in range(1, len(edges) - 144)
        if valid_frame_at(edges, sync)
    ]
    match = SLOT_PATTERN.search(os.path.basename(path))
    if not match:
        raise ValueError(f"unexpected slot filename: {path}")
    curtain = int(match.group(1))
    action = match.group(2)
    expected_frames = 6 if action == "stop" else 8
    expected_repeats = [6] if action == "stop" else [5, 3]
    payload_repeats = sorted(
        collections.Counter(decode_payload(edges, sync) for sync in syncs).values(),
        reverse=True,
    )
    if len(syncs) != expected_frames or payload_repeats != expected_repeats:
        raise ValueError(
            f"{path}: frames={len(syncs)} repeats={payload_repeats}, "
            f"expected frames={expected_frames} repeats={expected_repeats}"
        )

    durations = []
    for sync in syncs:
        frame_edges = list(edges[sync : sync + 145])
        frame_edges.append(edges[sync - 1])
        if len(frame_edges) != 146 or any(
            level != (1 if index % 2 == 0 else 0)
            for index, (_, level) in enumerate(frame_edges)
        ):
            raise ValueError(f"{path}: invalid clean frame polarity")
        durations.extend(duration for duration, _ in frame_edges)

    return {
        "curtain": curtain,
        "action": action,
        "frames": len(syncs),
        "durations": durations,
        "file_sha256": hashlib.sha256(open(path, "rb").read()).hexdigest(),
    }


def array_name(slot):
    return f"kCurtain{slot['curtain']:02d}{slot['action'].title()}Durations"


def write_header(output_path, slots, source_sha256):
    with open(output_path, "w", encoding="ascii") as output:
        output.write("// Generated by export_sticks3_codes.py. Do not edit.\n")
        output.write("#pragma once\n\n#include <stdint.h>\n\n")
        output.write("namespace curtain_rf_data {\n\n")
        output.write(f'inline constexpr char kSourceSha256[] = "{source_sha256}";\n\n')
        output.write("enum class Action : uint8_t { Up, Stop, Down };\n\n")
        output.write("struct Waveform {\n")
        output.write("  uint8_t curtain;\n  Action action;\n")
        output.write("  const uint16_t* durations;\n")
        output.write("  uint16_t edge_count;\n  uint8_t frame_count;\n")
        output.write("};\n\n")
        for slot in slots:
            output.write(f"inline constexpr uint16_t {array_name(slot)}[] = {{\n  ")
            for index, duration in enumerate(slot["durations"]):
                if index and index % 16 == 0:
                    output.write("\n  ")
                output.write(f"{duration}, ")
            output.write("\n};\n\n")
        output.write("inline constexpr Waveform kWaveforms[] = {\n")
        for slot in slots:
            action = slot["action"].title()
            output.write(
                f"  {{{slot['curtain']}, Action::{action}, {array_name(slot)}, "
                f"{len(slot['durations'])}, {slot['frames']}}},\n"
            )
        output.write("};\n\n")
        output.write("inline constexpr uint8_t kWaveformCount = ")
        output.write("sizeof(kWaveforms) / sizeof(kWaveforms[0]);\n\n")
        output.write("}  // namespace curtain_rf_data\n")


def main():
    parser = argparse.ArgumentParser(
        description="Export verified DC2702D captures as a StickS3 C++ header"
    )
    parser.add_argument("capture_dir")
    parser.add_argument("output")
    parser.add_argument("--source-image", required=True)
    args = parser.parse_args()

    paths = glob.glob(os.path.join(args.capture_dir, "latest_curtain_*.rfraw"))
    slots = sorted(
        (extract_slot(path) for path in paths),
        key=lambda slot: (slot["curtain"], ACTION_ORDER[slot["action"]]),
    )
    expected_slots = [
        (curtain, action)
        for curtain in range(1, 6)
        for action in ("up", "stop", "down")
    ]
    actual_slots = [(slot["curtain"], slot["action"]) for slot in slots]
    if actual_slots != expected_slots:
        raise SystemExit(f"incomplete slot catalog: {actual_slots}")

    with open(args.source_image, "rb") as source:
        source_sha256 = hashlib.sha256(source.read()).hexdigest()
    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    write_header(args.output, slots, source_sha256)
    print(
        f"exported {len(slots)} slots, "
        f"{sum(len(slot['durations']) for slot in slots)} edges, "
        f"source_sha256={source_sha256}"
    )


if __name__ == "__main__":
    main()
